"""Editable notation for task passages (admin editor).

Prose passages (`<div class="passage-body"><p>…</p>…</div>` with ruby furigana and evidence
spans) are shown to the admin as plain text:

    paragraphs separated by a blank line
    図書館《としょかん》        ruby: a kanji run followed by its reading
    ｜お願《ねが》い            "｜" marks where the base starts (base with kana, or a kanji
                               run that must not swallow preceding kanji)
    [ev-q1]…[/ev-q1]           evidence span used by the analysis "show evidence" locator

The conversion is lossless for the current content (html -> markup -> html is identical).
Passages with other markup (flyer tables, lists) are edited as HTML and sanitized against an
allow-list. Furigana are generated by the project tokenizer (pykakasi), never invented.
"""
import html as html_lib
import re
from html.parser import HTMLParser
from typing import List, Optional, Tuple

WRAPPER_OPEN = '<div class="passage-body">'
WRAPPER_CLOSE = '</div>'

_KANJI = "㐀-䶿一-鿿豈-﫿々〆ヶ"
_KANJI_RUN = re.compile(f"[{_KANJI}]+$")
_PURE_KANJI = re.compile(f"[{_KANJI}]+")
_EVIDENCE_ID = re.compile(r"^[A-Za-z0-9_-]{1,100}$")

# --------------------------------------------------------------------------- detection


_PROSE_TOKEN = re.compile(
    r'<ruby>[^<>]*<rt>[^<>]*</rt></ruby>'
    r'|<span id="([A-Za-z0-9_-]+)" data-evidence="\1">'
    r'|</span>'
    r'|[^<>]+'
)


def _inner_is_prose(inner: str) -> bool:
    pos = 0
    depth = 0
    while pos < len(inner):
        m = _PROSE_TOKEN.match(inner, pos)
        if not m:
            return False
        tok = m.group(0)
        if tok.startswith('<span'):
            depth += 1
        elif tok == '</span>':
            # a closing tag without an opening one is a known content defect (72 generated
            # texts); browsers ignore it, the editor drops it on save
            depth = max(0, depth - 1)
        pos = m.end()
    return depth == 0


def stray_span_closers(content_html: str) -> int:
    """Number of </span> without a matching <span> (ignored by browsers, dropped on save)."""
    depth = stray = 0
    for tok in re.findall(r"<span\b[^>]*>|</span>", content_html or ""):
        if tok == "</span>":
            if depth:
                depth -= 1
            else:
                stray += 1
        else:
            depth += 1
    return stray


_HEAD = re.compile(r'^(<div class="nhk-article-badge">[^<>]*</div>\n)')


def split_prose(content_html: str) -> Optional[Tuple[str, bool, List[str]]]:
    """Return (head, wrapped, [paragraph inner html]) if the passage is plain prose, else None.
    `head` is an optional fixed badge line (NHK) that is kept as is."""
    s = content_html or ""
    m = _HEAD.match(s)
    head = m.group(1) if m else ""
    s = s[len(head):]
    wrapped = s.startswith(WRAPPER_OPEN + "\n") and s.endswith("\n" + WRAPPER_CLOSE)
    body = s[len(WRAPPER_OPEN) + 1:-(len(WRAPPER_CLOSE) + 1)] if wrapped else s
    paras = re.findall(r"<p>(.*?)</p>", body, flags=re.DOTALL)
    rebuilt = "\n".join(f"<p>{p}</p>" for p in paras)
    if not paras or rebuilt != body:
        return None
    if not all(_inner_is_prose(p) and "\n" not in p for p in paras):
        return None
    return head, wrapped, paras


def passage_mode(content_html: str) -> str:
    return "markup" if split_prose(content_html) is not None else "html"


# --------------------------------------------------------------------------- html -> markup


def _para_to_markup(inner: str) -> str:
    out: List[str] = []
    stack: List[str] = []  # evidence spans may be nested
    for m in _PROSE_TOKEN.finditer(inner):
        tok = m.group(0)
        if tok.startswith('<ruby>'):
            base, reading = re.match(r"<ruby>([^<>]*)<rt>([^<>]*)</rt></ruby>", tok).groups()
            base, reading = html_lib.unescape(base), html_lib.unescape(reading)
            prev = out[-1][-1:] if out and out[-1] else ""
            needs_bar = not _PURE_KANJI.fullmatch(base) or bool(re.match(f"[{_KANJI}]", prev))
            out.append(("｜" if needs_bar else "") + f"{base}《{reading}》")
        elif tok.startswith('<span'):
            stack.append(m.group(1))
            out.append(f"[{m.group(1)}]")
        elif tok == '</span>':
            if stack:  # stray closers (see _inner_is_prose) are dropped
                out.append(f"[/{stack.pop()}]")
        else:
            out.append(html_lib.unescape(tok))
    return "".join(out)


def html_to_markup(content_html: str) -> Tuple[str, dict]:
    """Prose html -> (markup, frame). `frame` ({head, wrapped}) is passed back to
    markup_to_html unchanged. Raises ValueError for non-prose passages."""
    parts = split_prose(content_html)
    if parts is None:
        raise ValueError("passage is not plain prose")
    head, wrapped, paras = parts
    return "\n\n".join(_para_to_markup(p) for p in paras), {"head": head, "wrapped": wrapped}


# --------------------------------------------------------------------------- markup -> html

_MARKUP_TOKEN = re.compile(
    r"｜([^《》｜\[\]\n]+)《([^《》\n]*)》"      # explicit base
    r"|《([^《》\n]*)》"                         # reading after a kanji run
    r"|\[(/?)([A-Za-z0-9_-]{1,100})\]"           # evidence marker
)


class MarkupError(ValueError):
    pass


def _para_from_markup(text: str, line_no: int) -> str:
    out: List[str] = []          # html pieces
    plain: List[str] = []        # pending plain text (unescaped)
    stack: List[str] = []

    def flush():
        if plain:
            out.append(html_lib.escape("".join(plain), quote=False))
            plain.clear()

    pos = 0
    for m in _MARKUP_TOKEN.finditer(text):
        plain.append(text[pos:m.start()])
        pos = m.end()
        if m.group(1) is not None:
            flush()
            base, reading = m.group(1), m.group(2)
            if not reading:
                raise MarkupError(f"Абзац {line_no}: пустое чтение у «{base}»")
            out.append(f"<ruby>{html_lib.escape(base, quote=False)}<rt>{html_lib.escape(reading, quote=False)}</rt></ruby>")
        elif m.group(3) is not None:
            reading = m.group(3)
            pending = "".join(plain)
            run = _KANJI_RUN.search(pending)
            if not run:
                raise MarkupError(f"Абзац {line_no}: чтение 《{reading}》 стоит не после кандзи — используйте ｜слово《чтение》")
            if not reading:
                raise MarkupError(f"Абзац {line_no}: пустое чтение у «{run.group(0)}»")
            plain.clear()
            plain.append(pending[:run.start()])
            flush()
            out.append(f"<ruby>{html_lib.escape(run.group(0), quote=False)}<rt>{html_lib.escape(reading, quote=False)}</rt></ruby>")
        else:
            flush()
            closing, ev = m.group(4), m.group(5)
            if closing:
                if not stack or stack[-1] != ev:
                    raise MarkupError(f"Абзац {line_no}: [/{ev}] без парной открывающей метки")
                stack.pop()
                out.append("</span>")
            else:
                if ev in stack:
                    raise MarkupError(f"Абзац {line_no}: метка [{ev}] открыта повторно внутри самой себя")
                stack.append(ev)
                out.append(f'<span id="{ev}" data-evidence="{ev}">')
    plain.append(text[pos:])
    flush()
    if stack:
        raise MarkupError(f"Абзац {line_no}: метка [{stack[-1]}] не закрыта ([/{stack[-1]}])")
    joined = "".join(out)
    if "《" in joined or "》" in joined or "｜" in joined:
        raise MarkupError(f"Абзац {line_no}: непарные скобки 《 》 или лишний знак ｜")
    return joined


def markup_to_html(markup: str, frame: Optional[dict] = None) -> str:
    frame = frame or {"head": "", "wrapped": True}
    head = frame.get("head") or ""
    if head and not _HEAD.match(head):
        raise MarkupError("Неизвестная шапка текста")
    wrapped = bool(frame.get("wrapped", True))
    text = (markup or "").replace("\r\n", "\n").replace("\r", "\n")
    paras = [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]
    if not paras:
        raise MarkupError("Текст задания пустой")
    html_paras = []
    for i, p in enumerate(paras, 1):
        if "\n" in p:
            p = p.replace("\n", "")  # a single line break inside a paragraph is not meaningful in prose
        html_paras.append(f"<p>{_para_from_markup(p, i)}</p>")
    body = "\n".join(html_paras)
    return head + (f"{WRAPPER_OPEN}\n{body}\n{WRAPPER_CLOSE}" if wrapped else body)


def evidence_ids_in_html(content_html: str) -> List[str]:
    return re.findall(r'data-evidence="([^"]+)"', content_html or "")


# --------------------------------------------------------------------------- furigana


_tokenizer = None


def _janome():
    global _tokenizer
    if _tokenizer is None:
        from janome.tokenizer import Tokenizer  # morphological analyzer (dictionary readings)
        _tokenizer = Tokenizer()
    return _tokenizer


def _to_hiragana(s: str) -> str:
    return "".join(chr(ord(ch) - 0x60) if "ァ" <= ch <= "ヶ" else ch for ch in s)


def _ruby_word(surface: str, reading: str, prev: str) -> str:
    """Markup for one token: readings over kanji runs only, okurigana kept outside,
    e.g. 思いやり/おもいやり -> 思《おも》いやり, 取り組み/とりくみ -> 取《と》り組《く》み."""
    runs = re.findall(f"[{_KANJI}]+|[^{_KANJI}]+", surface)
    pattern = "".join("(.+?)" if re.match(f"[{_KANJI}]", r) else re.escape(_to_hiragana(r)) for r in runs)
    m = re.fullmatch(pattern, reading)
    if not m:
        needs_bar = not _PURE_KANJI.fullmatch(surface) or bool(re.match(f"[{_KANJI}]", prev))
        return ("｜" if needs_bar else "") + f"{surface}《{reading}》"
    out, groups = [], iter(m.groups())
    for r in runs:
        if re.match(f"[{_KANJI}]", r):
            last = (out[-1][-1:] if out and out[-1] else prev)
            bar = "｜" if re.match(f"[{_KANJI}]", last) else ""
            out.append(f"{bar}{r}《{next(groups)}》")
        else:
            out.append(r)
    return "".join(out)


def _ruby_for_plain(text: str) -> str:
    """Tokenizer furigana (janome dictionary readings) for plain text, returned as markup."""
    out: List[str] = []
    for tok in _janome().tokenize(text):
        surface, reading = tok.surface, tok.reading
        prev = out[-1][-1:] if out and out[-1] else ""
        if re.search(f"[{_KANJI}]", surface) and reading and reading != "*":
            out.append(_ruby_word(surface, _to_hiragana(reading), prev))
        else:
            out.append(surface)
    return "".join(out)


def add_missing_furigana(markup: str) -> str:
    """Add tokenizer readings to kanji that have none; existing readings and markers are kept."""
    lines = (markup or "").replace("\r\n", "\n").split("\n")
    result = []
    for line in lines:
        pieces = []
        pos = 0
        for m in _MARKUP_TOKEN.finditer(line):
            seg = line[pos:m.start()]
            if m.group(3) is not None:
                # 《reading》 right after plain kanji: keep that kanji run untouched
                run = _KANJI_RUN.search(seg)
                head = seg[:run.start()] if run else seg
                pieces.append(_ruby_for_plain(head) if head else "")
                pieces.append((run.group(0) if run else "") + m.group(0))
            else:
                pieces.append(_ruby_for_plain(seg) if seg else "")
                pieces.append(m.group(0))
            pos = m.end()
        tail = line[pos:]
        pieces.append(_ruby_for_plain(tail) if tail else "")
        result.append("".join(pieces))
    return "\n".join(result)


# --------------------------------------------------------------------------- html sanitizer

ALLOWED_TAGS = {
    "div", "p", "span", "ruby", "rt", "rp", "h2", "h3", "h4", "table", "thead", "tbody", "tr",
    "th", "td", "ul", "ol", "li", "strong", "em", "b", "i", "br", "small",
}
VOID_TAGS = {"br"}
ALLOWED_ATTRS = {"class", "id", "data-evidence", "colspan", "rowspan"}
_SAFE_ATTR_VALUE = re.compile(r"^[A-Za-z0-9 _:-]{0,200}$")
_DROP_CONTENT = {"script", "style", "iframe", "object", "embed", "template", "noscript", "svg", "math"}


class _Sanitizer(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=False)
        self.out: List[str] = []
        self.skip_depth = 0
        self.removed: List[str] = []

    def handle_starttag(self, tag, attrs):
        if tag in _DROP_CONTENT:
            self.skip_depth += 1
            self.removed.append(tag)
            return
        if self.skip_depth:
            return
        if tag not in ALLOWED_TAGS:
            self.removed.append(tag)
            return
        kept = []
        for name, value in attrs:
            if name in ALLOWED_ATTRS and value is not None and _SAFE_ATTR_VALUE.match(value):
                kept.append(f' {name}="{value}"')
            else:
                self.removed.append(f"{tag}[{name}]")
        self.out.append(f"<{tag}{''.join(kept)}>")

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)

    def handle_endtag(self, tag):
        if tag in _DROP_CONTENT:
            self.skip_depth = max(0, self.skip_depth - 1)
            return
        if self.skip_depth or tag not in ALLOWED_TAGS or tag in VOID_TAGS:
            return
        self.out.append(f"</{tag}>")

    def handle_data(self, data):
        if not self.skip_depth:
            self.out.append(html_lib.escape(data, quote=False))

    def handle_entityref(self, name):
        if not self.skip_depth:
            self.out.append(f"&{name};")

    def handle_charref(self, name):
        if not self.skip_depth:
            self.out.append(f"&#{name};")

    def handle_comment(self, data):
        self.removed.append("comment")


def sanitize_passage_html(raw: str) -> Tuple[str, List[str]]:
    """Allow-list sanitizer for admin-edited passage HTML. Returns (html, removed items)."""
    p = _Sanitizer()
    p.feed(raw or "")
    p.close()
    return "".join(p.out).strip(), p.removed
